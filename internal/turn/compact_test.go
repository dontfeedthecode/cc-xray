// replay feeds inline JSONL through a fresh Builder.
func replay(t *testing.T, lines string) *Builder {
	t.Helper()
	b := New()
	for _, l := range strings.Split(strings.TrimSpace(lines), "\n") {
		if l = strings.TrimSpace(l); l == "" {
			continue
		}
		var r record.Record
		if err := json.Unmarshal([]byte(l), &r); err != nil {
			t.Fatalf("fixture line: %v\n%s", err, l)
		}
		b.Add(r)
	}
	return b
}

